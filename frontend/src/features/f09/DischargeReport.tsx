import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { get, openStoredFile, post } from "../../api";
import { currentRole } from "../../components/roles";

type Report = { event_id: string; document_id: string; time: string; by: string };

const when = (iso: string) => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString(undefined, { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
};

/** Discharge summary in the hospital format, generated from the whole record. Doctors generate; everyone views. */
export function DischargeReport() {
  const queryClient = useQueryClient();
  const canGenerate = ["admin", "senior", "junior"].includes(currentRole());
  const reports = useQuery({ queryKey: ["discharge-reports"], queryFn: () => get<{ reports: Report[] }>("/discharge/reports") });
  const generate = useMutation({
    mutationFn: () => post<{ document_id: string }>("/discharge/report"),
    onSuccess: async (done) => {
      await queryClient.invalidateQueries();
      openStoredFile(done.document_id).catch(() => undefined);
    },
  });
  const list = reports.data?.reports || [];

  return (
    <div className="progress-notes">
      <div className="card">
        <div className="card-header">
          <h2>Discharge summary</h2>
          {canGenerate ? (
            <button className="btn btn-primary btn-sm" onClick={() => generate.mutate()} disabled={generate.isPending} aria-busy={generate.isPending || undefined}>
              {generate.isPending ? <><span className="spinner" /> Generating...</> : "Generate report"}
            </button>
          ) : null}
        </div>
        <div className="card-body">
          <span className="small muted">
            {canGenerate
              ? "Builds the summary from the patient's signed notes, vitals, results and medicines: progress note (SOAP) and doctors handoff. It is stored on the timeline. Lines not in the record print as \"Not documented\"."
              : "Discharge summaries are generated by doctors. You can open any report below."}
          </span>
          {generate.isError ? <div className="error-box" role="alert">{String((generate.error as Error)?.message || generate.error)}</div> : null}
        </div>
      </div>

      <div className="card">
        <div className="card-header"><h2>Reports</h2></div>
        <div className="table-wrap">
          <table className="table progress-table">
            <thead><tr><th>Date and time</th><th>Generated by</th><th /></tr></thead>
            <tbody>
              {list.map((r) => (
                <tr key={r.event_id}>
                  <td>{when(r.time)}</td>
                  <td>{r.by}</td>
                  <td><button className="btn btn-sm" onClick={() => openStoredFile(r.document_id)}>View / Print</button></td>
                </tr>
              ))}
              {!list.length ? <tr><td colSpan={3} className="muted small">{reports.isLoading ? "Loading..." : "No discharge summary yet."}</td></tr> : null}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
